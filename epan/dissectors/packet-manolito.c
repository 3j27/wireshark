/* --- manolito checksum core: begin --- */

/* CRC-16/CCITT: poly 0x1021, MSB first, init 0, no final xor. */
#define MANOLITO_CRC16_POLY	0x1021
#define MANOLITO_CRC16_INIT	0x0000

static uint16_t
manolito_crc16_byte(uint16_t crc, uint8_t byte)
{
	unsigned bit;

	crc ^= (uint16_t)byte << 8;
	for (bit = 0; bit < 8; bit++) {
		if (crc & 0x8000)
			crc = (uint16_t)((crc << 1) ^ MANOLITO_CRC16_POLY);
		else
			crc = (uint16_t)(crc << 1);
	}
	return crc;
}

/*
 * Candidate sender code pages.  The sender (a VB6 program) hashes the
 * UTF-16LE bytes of the message's ANSI decoding, so every message byte
 * >= 0x80 takes part in the checksum as the Unicode character its own
 * code page assigns to it.  high[] maps 0x80..0xff; NULL means the
 * identity map (ISO-8859-1).  Bytes the code page leaves undefined keep
 * their byte value, which is what MultiByteToWideChar() does for them.
 * The order here defines the bits of the match mask.
 */
